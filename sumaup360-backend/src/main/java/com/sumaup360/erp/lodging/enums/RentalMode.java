package com.sumaup360.erp.lodging.enums;

/**
 * Modalidad de alquiler de la estadia. NIGHTLY cobra por noches (salida
 * exclusiva); HOURLY es el alquiler por horas del hospedaje peruano: entra y
 * sale el mismo dia, no bloquea fechas futuras y ocupa la habitacion solo
 * mientras dura el check-in.
 */
public enum RentalMode {
    NIGHTLY,
    HOURLY
}
